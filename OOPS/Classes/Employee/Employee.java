class Employee {
    String name;
    int empID;
    double salary;
    String designation;
    public void getInformation() {
        System.out.println("Employee Name : " + name);
        System.out.println("Employee ID   : " + empID);
        System.out.println("Salary        : " + salary);
        System.out.println("Designation   : " + designation);
    }
}