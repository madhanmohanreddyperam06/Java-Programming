// using switch case, find the alphabet is vowel or consonant

public class SwitchVowel{
    public static void main(String[] args){
        char ch='I';
        switch(ch){
            case 'A':{
                System.out.println("Vowel");
                break;
            }case 'E':{
                System.out.println("Vowel");
                break;
            }case 'I':{
                System.out.println("Vowel");
                break;
            }case 'O':{
                System.out.println("Vowel");
                break;
            }case 'U':{
                System.out.println("Vowel");
                break;
            }case 'a':{
                System.out.println("Vowel");
                break;
            }case 'e':{
                System.out.println("Vowel");
            }case 'i':{
                System.out.println("vowel");
                break;
            }case 'o':{
                System.out.println("Vowel");
                break;
            }case 'u':{
                System.out.println("Vowel");
            }default:{
                System.out.println("Consonant");
            }
        }
    }
}
